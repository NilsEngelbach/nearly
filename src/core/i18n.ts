export let lang: Lang = 'en';
export let t: Strings = en;
const listeners = new Set<() => void>();

export function detectLang(): Lang {
  return (navigator.languages ?? [navigator.language]).some((l) => l?.toLowerCase().startsWith('de')) ? 'de' : 'en';
}

export function setLang(l: Lang) {
  lang = l;
  t = l === 'de' ? de : en;
  document.documentElement.lang = l;
  for (const fn of listeners) fn();
}

export function onLang(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export const num = (v: number, digits = 0) =>
  v.toLocaleString(lang === 'de' ? 'de-DE' : 'en-GB', { minimumFractionDigits: digits, maximumFractionDigits: digits });
